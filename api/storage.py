"""SQLite for local use; private PostgreSQL storage for hosted pilots.

Writes retain the original single-writer semantics with a transaction-scoped
advisory lock. This is deliberately a small pilot, not a scaled dispatch system.
"""
from contextlib import contextmanager
from pathlib import Path
import re
import sqlite3

import psycopg
from psycopg import sql

INTEGRITY_ERRORS = (sqlite3.IntegrityError, psycopg.IntegrityError)
LOCK_KEY = 7247981


class Row(dict):
    def __getitem__(self, key):
        return tuple(self.values())[key] if isinstance(key, int) else super().__getitem__(key)


def row_factory(cursor):
    names = [column.name for column in cursor.description] if cursor.description else []
    return lambda values: Row(zip(names, values))


def placeholders(statement):
    """Translate only unquoted qmark parameters; never interpolate values."""
    chunks = re.split(r"('(?:''|[^'])*'|\"(?:\"\"|[^\"])*\")", statement)
    return ''.join(part.replace('%', '%%').replace('?', '%s') if i % 2 == 0
                   else part.replace('%', '%%') for i, part in enumerate(chunks))


class Postgres:
    def __init__(self, connection):
        self.connection = connection

    def execute(self, statement, parameters=None):
        # The only type differences in our shared, application-owned schema.
        if statement.lstrip().upper().startswith('CREATE TABLE'):
            statement = re.sub(r'\bINTEGER PRIMARY KEY\b',
                               'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', statement)
            statement = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', statement)
        if parameters is None:
            return self.connection.execute(statement)
        return self.connection.execute(placeholders(statement), parameters)


def install(connection, script):
    # These schema constants contain no SQL functions or semicolons in strings.
    # Unlike sqlite executescript, this preserves the caller's transaction.
    for statement in script.split(';'):
        if statement.strip():
            connection.execute(statement)


@contextmanager
def connect(path, database_url='', write=False, schema='planto', initialize=False):
    if not database_url:
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        c = sqlite3.connect(path, timeout=15, isolation_level=None)
        c.row_factory = sqlite3.Row
        try:
            c.execute('PRAGMA foreign_keys=ON')
            if initialize:
                c.execute('PRAGMA journal_mode=WAL')
            if write:
                c.execute('BEGIN IMMEDIATE')
            yield c
            if write:
                c.commit()
        except Exception:
            if write:
                c.rollback()
            raise
        finally:
            c.close()
        return

    if not re.fullmatch(r'planto(?:_test_[a-z0-9]+)?', schema):
        raise ValueError('Use the private planto schema or an isolated test schema.')
    if not database_url.startswith(('postgresql://', 'postgres://')):
        raise ValueError('DATABASE_URL must be a PostgreSQL connection URL.')
    with psycopg.connect(database_url, autocommit=True, connect_timeout=10,
                         prepare_threshold=None, row_factory=row_factory) as c:
        c.execute("SET statement_timeout='20s'")
        c.execute("SET lock_timeout='15s'")
        # Every operation has an explicit transaction; no session lock leaks
        # through the Supabase pooler, including when an exception is raised.
        with c.transaction():
            if write:
                c.execute('SELECT pg_advisory_xact_lock(%s)', (LOCK_KEY,))
            if initialize:
                if not c.execute('SELECT 1 FROM pg_namespace WHERE nspname=%s', (schema,)).fetchone():
                    c.execute(sql.SQL('CREATE SCHEMA {}').format(sql.Identifier(schema)))
                c.execute(sql.SQL('REVOKE ALL ON SCHEMA {} FROM PUBLIC').format(sql.Identifier(schema)))
                for role in ('anon', 'authenticated'):
                    if c.execute('SELECT 1 FROM pg_roles WHERE rolname=%s', (role,)).fetchone():
                        c.execute(sql.SQL('REVOKE ALL ON SCHEMA {} FROM {}').format(
                            sql.Identifier(schema), sql.Identifier(role)))
            c.execute(sql.SQL('SET LOCAL search_path TO {}, pg_catalog').format(sql.Identifier(schema)))
            yield Postgres(c)
            if initialize:
                # The runtime owns these tables; unprivileged API roles receive
                # neither schema access nor row policies.
                for row in c.execute('SELECT tablename FROM pg_tables WHERE schemaname=%s', (schema,)).fetchall():
                    c.execute(sql.SQL('ALTER TABLE {}.{} ENABLE ROW LEVEL SECURITY').format(
                        sql.Identifier(schema), sql.Identifier(row['tablename'])))
